CREATE TABLE IF NOT EXISTS erp_keys (
 id CHAR(36) PRIMARY KEY, tenant_id CHAR(36) NOT NULL, token_hash CHAR(64) UNIQUE NOT NULL,
 scope VARCHAR(40) NOT NULL, revoked BOOLEAN NOT NULL DEFAULT FALSE,
 window_minute BIGINT NOT NULL DEFAULT 0, used INT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(tenant_id)
) ENGINE=InnoDB;
